package praticas.sets.taskmanangement.enums;

/**
 * Representa os níveis de prioridade de uma tarefa.
 *
 * A prioridade pode ser utilizada para organizar, classificar
 * ou definir a ordem de execução das tarefas.
 *
 */
public enum Priority {

    /** Prioridade alta. */
    ALTA,

    /** Prioridade média. */
    MÉDIA,

    /** Prioridade baixa. */
    BAIXA
}
