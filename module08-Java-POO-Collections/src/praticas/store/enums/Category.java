package praticas.store.enums;

/**
 * Representa as categorias de produtos disponíveis no estoque.
 *
 * As categorias permitem organizar os produtos em grupos de acordo
 * com sua natureza, facilitando sua classificação e gerenciamento.
 *
 */
public enum Category {

    /** Frutas, verduras, legumes e demais produtos . */
    HORTIFRUTI,

    /** Leite, queijos, iogurtes e outros produtos lácteos. */
    LATICINIO,

    /** Cereais, grãos e derivados. */
    CEREAL,

    /** Carnes e produtos de origem animal. */
    CARNES,

    /** Bebidas em geral. */
    BEBIDAS
}